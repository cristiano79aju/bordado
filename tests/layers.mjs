import assert from 'node:assert/strict';
import {planLayers,setLayerVisibility,setLayerLock,validateLayerPlan} from '../dist/layer-planner.mjs';
const region=(id,x,y,w,h,color)=>({id,name:id,kind:'fill',color,x:0,y:0,paths:[{points:[{x,y},{x:x+w,y},{x:x+w,y:y+h},{x,y:y+h}]}]});
const bg=region('bg',0,0,100,100,'#2244aa');
const leaf=region('leaf',15,20,40,50,'#228844');
const flower=region('flower',25,25,12,12,'#cc2244');
const badge=region('badge',75,5,10,10,'#cc2244');
const source=[flower,bg,badge,leaf],plan=planLayers(source);
assert.equal(plan.summary.objects,4);
assert(plan.summary.layers>=2);
assert(plan.order.indexOf('bg')<plan.order.indexOf('leaf'));
assert(plan.order.indexOf('leaf')<plan.order.indexOf('flower'));
assert.deepEqual(validateLayerPlan(source,plan).issues,[]);
assert.equal(new Set(plan.order).size,source.length);
const flowerLayer=flower.layerId;
setLayerVisibility(source,flowerLayer,false);assert.equal(flower.visible,false);
setLayerLock(source,flowerLayer,true);assert.equal(flower.layerLocked,true);
const independent=[region('a',0,0,8,8,'#ff0000'),region('b',20,0,8,8,'#ff0000')];
const p2=planLayers(independent);assert.equal(p2.summary.objects,2);assert.deepEqual(validateLayerPlan(independent,p2).issues,[]);
const noBounds=planLayers([{id:'unknown',kind:'fill',paths:[]}]);assert.equal(noBounds.summary.objects,1);assert(validateLayerPlan([{id:'unknown',kind:'fill',paths:[]}],noBounds).issues.some(x=>x.type==='missing-object'));
console.log('Layer planner tests passed:',JSON.stringify({summary:plan.summary,order:plan.order,dependencies:plan.dependencies.length}));
